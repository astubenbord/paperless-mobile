import 'dart:async';

import 'package:flutter/material.dart';
import 'package:flutter_bloc/flutter_bloc.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:paperless_mobile/api/paperless_api.dart';
import 'package:paperless_mobile/core/service/connectivity_status_service.dart';
import 'package:paperless_mobile/features/document_chat/cubit/document_chat_cubit.dart';
import 'package:paperless_mobile/features/document_chat/view/document_chat_page.dart';
import 'package:paperless_mobile/generated/l10n/app_localizations.dart';
import 'package:provider/provider.dart';

class _FakeChatApi implements PaperlessChatApi {
  final answer = StreamController<DocumentChatResponse>();

  @override
  Stream<DocumentChatResponse> chat(String question, {int? documentId}) =>
      answer.stream;
}

class _OnlineConnectivityStatusService implements ConnectivityStatusService {
  @override
  Stream<bool> connectivityChanges() => Stream.value(true);

  @override
  dynamic noSuchMethod(Invocation invocation) => super.noSuchMethod(invocation);
}

void main() {
  testWidgets('asks a question and shows the streamed answer with sources', (
    tester,
  ) async {
    final api = _FakeChatApi();
    await tester.pumpWidget(
      Provider<ConnectivityStatusService>(
        create: (_) => _OnlineConnectivityStatusService(),
        child: MaterialApp(
          localizationsDelegates: S.localizationsDelegates,
          supportedLocales: S.supportedLocales,
          home: BlocProvider(
            create: (_) => DocumentChatCubit(api, documentId: 1),
            child: const DocumentChatPage(documentTitle: 'Invoice'),
          ),
        ),
      ),
    );
    await tester.pumpAndSettle();

    expect(find.text('Chat with this document'), findsOneWidget);
    expect(find.text('Invoice'), findsOneWidget);
    expect(find.textContaining('Answers are generated by AI'), findsOneWidget);

    await tester.enterText(find.byType(TextField), 'When is it due?');
    await tester.pump();
    await tester.tap(find.byTooltip('Send'));
    await tester.pump();

    expect(find.text('When is it due?'), findsOneWidget);
    expect(find.byType(CircularProgressIndicator), findsOneWidget);

    api.answer.add(
      DocumentChatResponse(
        content: 'It is due tomorrow.',
        references: [DocumentChatReference(id: 1, title: 'Invoice 2026')],
      ),
    );
    await api.answer.close();
    await tester.pumpAndSettle();

    expect(find.text('It is due tomorrow.'), findsOneWidget);
    expect(find.text('Sources'), findsOneWidget);
    expect(find.widgetWithText(ActionChip, 'Invoice 2026'), findsOneWidget);
    expect(find.byType(CircularProgressIndicator), findsNothing);
  });
}
